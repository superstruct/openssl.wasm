class OpenSSLWASMNativeTester {
    constructor() {
        this.testResults = [];
        this.openssl = null;
    }
    
    async runAllTests() {
        console.log('🔐 OpenSSL WASM-Native Comprehensive Test Suite');
        console.log('='.repeat(60));
        
        try {
            await this.testInitialization();
            await this.testCertificateLoading();
            await this.testPersistentCache();
            await this.testAsyncLoading();
            await this.testSecurityControls();
            await this.testCertificatePackages();
            await this.testErrorHandling();
            await this.testPerformance();
            await this.testCleanup();
            
        } catch (error) {
            console.error('🚨 Test suite failed:', error);
            this.logResult('Test Suite', false, error.message);
        }
        
        this.printSummary();
    }
    
    async testInitialization() {
        console.log('\n📋 Test: Initialization');
        
        try {
            // Load WASM module
            const module = await OpenSSLModule();
            this.openssl = new OpenSSLWASMNative(module);
            
            // Test initialization with secure configuration
            const result = await this.openssl.initialize({
                persistentCache: true,
                encryptClientCerts: true,
                verifyCertificateIntegrity: true,
                maxCacheSize: 10,
                maxCacheAge: 24 * 60 * 60 * 1000, // 24 hours
                trustedCdnSources: ['mozilla.org', 'letsencrypt.org', 'curl.se']
            });
            
            if (!result.success) {
                throw new Error(`Initialization failed: ${result.error}`);
            }
            
            const features = this.openssl.getEnabledFeatures();
            console.log('✅ Initialized with features:', features);
            
            // Verify critical security settings
            if (features.persistentCache && features.verifyCertificateIntegrity) {
                this.logResult('Initialization', true, 'All security features enabled');
            } else {
                this.logResult('Initialization', false, 'Security features not properly enabled');
            }
            
        } catch (error) {
            this.logResult('Initialization', false, error.message);
            throw error;
        }
    }
    
    async testCertificateLoading() {
        console.log('\n📜 Test: Certificate Loading');
        
        try {
            // Test 1: Load from buffer
            console.log('🔍 Test 1.1: Load certificate from buffer');
            
            // Create a dummy certificate for testing (in real use, this would be actual cert data)
            const dummyCertBuffer = new TextEncoder().encode(
                '-----BEGIN CERTIFICATE-----\n' +
                'MIIBkTCB+wIJAKZFZGZFZGZFMA0GCSqGSIb3DQEBCwUAMBQxEjAQBgNVBAMMCVRl\n' +
                'c3QgQ2VydDAeFw0yNTA5MDUxMjAwMDBaFw0yNjA5MDUxMjAwMDBaMBQxEjAQBgNV\n' +
                'BAMMCVRlc3QgQ2VydDBcMA0GCSqGSIb3DQEBAQUAA0sAMEgCQQC7VJTUt9Us8XXP\n' +
                '-----END CERTIFICATE-----\n'
            );
            
            // Note: This is a dummy certificate for testing
            // In production, use real certificates and proper validation
            try {
                const certId = await this.openssl.loadCertificateFromBuffer(
                    dummyCertBuffer, 
                    'test-cert-1',
                    { verifyCertificateIntegrity: false } // Skip validation for dummy cert
                );
                console.log('✅ Certificate loaded from buffer:', certId);
            } catch (error) {
                console.log('⚠️ Buffer loading test skipped (dummy certificate)');
            }
            
            // Test 2: Load default CA bundle (if preloaded)
            console.log('🔍 Test 1.2: Load default CA bundle');
            const certificates = this.openssl.listLoadedCertificates();
            console.log('📋 Currently loaded certificates:', certificates.length);
            
            this.logResult('Certificate Loading', true, `Loaded ${certificates.length} certificates`);
            
        } catch (error) {
            this.logResult('Certificate Loading', false, error.message);
        }
    }
    
    async testPersistentCache() {
        console.log('\n💾 Test: Persistent Cache');
        
        try {
            // Test cache functionality
            const testData = new TextEncoder().encode('test-certificate-data');
            const cacheKey = 'test-cache-key';
            
            // Store in cache
            await this.openssl.certificateCache.set(cacheKey, {
                data: testData,
                loadedAt: Date.now(),
                url: 'https://example.com/cert.pem'
            });
            
            console.log('✅ Data stored in cache');
            
            // Retrieve from cache
            const cached = await this.openssl.certificateCache.get(cacheKey);
            
            if (cached && cached.data) {
                const retrievedText = new TextDecoder().decode(cached.data);
                const originalText = new TextDecoder().decode(testData);
                
                if (retrievedText === originalText) {
                    console.log('✅ Data retrieved correctly from cache');
                    this.logResult('Persistent Cache', true, 'Cache read/write successful');
                } else {
                    this.logResult('Persistent Cache', false, 'Cache data corruption');
                }
            } else {
                this.logResult('Persistent Cache', false, 'Failed to retrieve cached data');
            }
            
        } catch (error) {
            this.logResult('Persistent Cache', false, error.message);
        }
    }
    
    async testAsyncLoading() {
        console.log('\n🌐 Test: Async Certificate Loading');
        
        try {
            // Test loading from a real URL (Let's Encrypt root certificate)
            console.log('🔍 Testing async loading from Let\'s Encrypt...');
            
            const letsEncryptUrl = 'https://letsencrypt.org/certs/isrgrootx1.pem';
            
            try {
                const certId = await this.openssl.loadCertificateFromUrl(
                    letsEncryptUrl,
                    'letsencrypt-root-test'
                );
                
                console.log('✅ Certificate loaded asynchronously:', certId);
                
                // Verify certificate info
                const certInfo = this.openssl.getCertificateInfo(certId);
                if (certInfo) {
                    console.log('📋 Certificate info:', {
                        id: certInfo.id,
                        size: certInfo.size,
                        loadedAt: new Date(certInfo.loadedAt).toISOString()
                    });
                }
                
                this.logResult('Async Loading', true, 'Successfully loaded from URL');
                
            } catch (urlError) {
                console.log('⚠️ URL loading test failed (network/CORS):', urlError.message);
                this.logResult('Async Loading', 'skipped', 'Network access required');
            }
            
        } catch (error) {
            this.logResult('Async Loading', false, error.message);
        }
    }
    
    async testSecurityControls() {
        console.log('\n🔒 Test: Security Controls');
        
        try {
            const testsPassed = [];
            
            // Test 1: Private key security
            console.log('🔍 Test 4.1: Private key security');
            
            const testKeyData = new TextEncoder().encode('test-private-key-data');
            const keyPath = this.openssl.privateKeyManager.storePrivateKey(
                'test-key', 
                testKeyData,
                'test-passphrase'
            );
            
            if (keyPath && keyPath.includes('/ssl-temp/')) {
                console.log('✅ Private key stored in temporary location');
                testsPassed.push('Private key location');
                
                // Verify it's not in persistent cache
                if (!keyPath.includes('/ssl-cache/')) {
                    console.log('✅ Private key NOT in persistent storage');
                    testsPassed.push('Private key non-persistence');
                } else {
                    console.log('🚨 SECURITY VIOLATION: Private key in persistent storage!');
                }
            }
            
            // Test 2: Configuration validation
            console.log('🔍 Test 4.2: Configuration validation');
            
            const features = this.openssl.getEnabledFeatures();
            if (features.verifyCertificateIntegrity) {
                console.log('✅ Certificate integrity verification enabled');
                testsPassed.push('Integrity verification');
            }
            
            if (features.encryptClientCerts) {
                console.log('✅ Client certificate encryption enabled');
                testsPassed.push('Client cert encryption');
            }
            
            // Test 3: Trusted sources validation
            console.log('🔍 Test 4.3: Trusted sources validation');
            
            try {
                await this.openssl.loadCertificateFromUrl(
                    'https://untrusted-domain.example.com/cert.pem',
                    'untrusted-test'
                );
                console.log('🚨 SECURITY ISSUE: Untrusted domain accepted');
            } catch (securityError) {
                if (securityError.message.includes('Untrusted')) {
                    console.log('✅ Untrusted domain properly rejected');
                    testsPassed.push('Domain validation');
                }
            }
            
            this.logResult('Security Controls', true, `Passed ${testsPassed.length}/4 security tests`);
            
        } catch (error) {
            this.logResult('Security Controls', false, error.message);
        }
    }
    
    async testCertificatePackages() {
        console.log('\n📦 Test: Certificate Packages');
        
        try {
            console.log('🔍 Testing certificate package system...');
            
            // This test would require actual package files
            // For now, test the package loading interface
            
            const mockPackageUrl = 'https://example.com/cert-package.zip';
            
            try {
                const certificates = await this.openssl.loadCertificatePackage(
                    mockPackageUrl,
                    'test-package'
                );
                
                console.log('✅ Package loading interface works');
                this.logResult('Certificate Packages', true, 'Interface functional');
                
            } catch (packageError) {
                // Expected to fail with mock URL
                console.log('⚠️ Package loading test requires real package files');
                this.logResult('Certificate Packages', 'skipped', 'Mock package used');
            }
            
        } catch (error) {
            this.logResult('Certificate Packages', false, error.message);
        }
    }
    
    async testErrorHandling() {
        console.log('\n🚨 Test: Error Handling');
        
        try {
            const errorTests = [];
            
            // Test 1: Invalid certificate buffer
            console.log('🔍 Test 6.1: Invalid certificate handling');
            
            try {
                await this.openssl.loadCertificateFromBuffer(
                    new Uint8Array([1, 2, 3, 4]), // Invalid certificate data
                    'invalid-cert'
                );
                console.log('🚨 ERROR: Invalid certificate was accepted');
            } catch (certError) {
                console.log('✅ Invalid certificate properly rejected');
                errorTests.push('Invalid certificate rejection');
            }
            
            // Test 2: Empty buffer
            console.log('🔍 Test 6.2: Empty buffer handling');
            
            try {
                await this.openssl.loadCertificateFromBuffer(
                    new Uint8Array([]),
                    'empty-cert'
                );
                console.log('🚨 ERROR: Empty buffer was accepted');
            } catch (emptyError) {
                console.log('✅ Empty buffer properly rejected');
                errorTests.push('Empty buffer rejection');
            }
            
            // Test 3: Network error simulation
            console.log('🔍 Test 6.3: Network error handling');
            
            try {
                await this.openssl.loadCertificateFromUrl(
                    'https://nonexistent-domain-12345.com/cert.pem',
                    'network-error-test'
                );
                console.log('🚨 ERROR: Network error not handled');
            } catch (networkError) {
                console.log('✅ Network error properly handled');
                errorTests.push('Network error handling');
            }
            
            this.logResult('Error Handling', true, `Passed ${errorTests.length}/3 error tests`);
            
        } catch (error) {
            this.logResult('Error Handling', false, error.message);
        }
    }
    
    async testPerformance() {
        console.log('\n⚡ Test: Performance Metrics');
        
        try {
            const metrics = {
                cacheOperations: 0,
                certificateOps: 0,
                memoryUsage: 0
            };
            
            // Test cache performance
            console.log('🔍 Testing cache performance...');
            
            const startTime = Date.now();
            const testData = new TextEncoder().encode('performance-test-data');
            
            // Perform multiple cache operations
            for (let i = 0; i < 10; i++) {
                await this.openssl.certificateCache.set(`perf-test-${i}`, {
                    data: testData,
                    loadedAt: Date.now()
                });
                
                const retrieved = await this.openssl.certificateCache.get(`perf-test-${i}`);
                if (retrieved) {
                    metrics.cacheOperations++;
                }
            }
            
            const endTime = Date.now();
            const duration = endTime - startTime;
            
            console.log(`✅ Cache performance: ${metrics.cacheOperations} ops in ${duration}ms`);
            console.log(`   Average: ${(duration / metrics.cacheOperations).toFixed(2)}ms per operation`);
            
            // Memory usage approximation
            const certificates = this.openssl.listLoadedCertificates();
            const totalSize = certificates.reduce((sum, cert) => sum + cert.size, 0);
            
            console.log(`📊 Memory usage: ~${(totalSize / 1024).toFixed(2)} KB for ${certificates.length} certificates`);
            
            this.logResult('Performance', true, `${duration}ms for ${metrics.cacheOperations} operations`);
            
        } catch (error) {
            this.logResult('Performance', false, error.message);
        }
    }
    
    async testCleanup() {
        console.log('\n🧹 Test: Cleanup and Security');
        
        try {
            console.log('🔍 Testing secure cleanup...');
            
            // Get initial state
            const initialCerts = this.openssl.listLoadedCertificates();
            console.log(`📋 Certificates before cleanup: ${initialCerts.length}`);
            
            // Perform cleanup
            this.openssl.cleanup();
            
            // Verify cleanup
            const finalCerts = this.openssl.listLoadedCertificates();
            console.log(`📋 Certificates after cleanup: ${finalCerts.length}`);
            
            if (finalCerts.length === 0) {
                console.log('✅ All certificates properly cleaned up');
                this.logResult('Cleanup', true, 'All resources cleaned');
            } else {
                console.log('⚠️ Some certificates remain after cleanup');
                this.logResult('Cleanup', false, `${finalCerts.length} certificates remain`);
            }
            
        } catch (error) {
            this.logResult('Cleanup', false, error.message);
        }
    }
    
    logResult(testName, success, details) {
        this.testResults.push({
            test: testName,
            success: success,
            details: details,
            timestamp: new Date().toISOString()
        });
    }
    
    printSummary() {
        console.log('\n' + '='.repeat(60));
        console.log('🏆 OpenSSL WASM-Native Test Summary');
        console.log('='.repeat(60));
        
        const passed = this.testResults.filter(r => r.success === true).length;
        const failed = this.testResults.filter(r => r.success === false).length;
        const skipped = this.testResults.filter(r => r.success === 'skipped').length;
        const total = this.testResults.length;
        
        console.log(`\n📊 Results: ${passed}/${total} passed, ${failed} failed, ${skipped} skipped\n`);
        
        this.testResults.forEach(result => {
            const status = result.success === true ? '✅' : 
                          result.success === false ? '❌' : '⚠️';
            console.log(`${status} ${result.test}: ${result.details}`);
        });
        
        console.log('\n🔒 Security Status:');
        const securityTests = this.testResults.filter(r => 
            r.test.includes('Security') || r.test.includes('Private')
        );
        const securityPassed = securityTests.filter(r => r.success === true).length;
        
        if (securityPassed === securityTests.length && securityTests.length > 0) {
            console.log('   ✅ All security tests passed - System secure');
        } else {
            console.log('   🚨 Security issues detected - Review required');
        }
        
        console.log('\n💾 Performance Summary:');
        const perfTest = this.testResults.find(r => r.test === 'Performance');
        if (perfTest && perfTest.success) {
            console.log(`   ⚡ Cache operations: ${perfTest.details}`);
        }
        
        console.log('\n🎯 Recommendations:');
        if (failed > 0) {
            console.log('   • Address failed tests before production use');
        }
        if (skipped > 0) {
            console.log('   • Consider implementing skipped functionality');
        }
        console.log('   • Regularly update CA certificate bundles');
        console.log('   • Monitor cache size and performance');
        console.log('   • Implement proper error handling in production');
        
        console.log('\n' + '='.repeat(60));
    }
}

